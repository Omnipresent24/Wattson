package com.bydmate.app.motorklang

/**
 * WATTSON fork: Motorklang engine profiles, ported from the Motorklang web prototype.
 *
 * Every value is the prototype's; [fm] holds three formant resonances (Hz, gain dB, Q).
 * [vmax] is the sound car's top speed: 100 % of the real car's top speed maps onto it, so the
 * sound car runs through its gears over the same share of its range as the real one.
 */
data class EngineProfile(
    val id: String,
    val name: String,
    val category: String,
    val spec: String,
    val cylinders: Int,
    val redline: Int,
    val idle: Int,
    val shiftLow: Int,
    val gears: List<Double>,
    val finalDrive: Double,
    val vmax: Int,
    val banks: List<Int>? = null,
    val cross: Double = 0.0,
    val offsets: List<Double>? = null,
    val amps: List<Double>? = null,
    val pulse: Double = 1.0,
    val sharp: Double = 1.0,
    val lope: Double = 0.08,
    val noise: Double = 0.25,
    /** "na", "turbo" or "sc" (supercharger). */
    val induction: String = "na",
    val turbo: Double = 0.0,
    val supercharger: Double = 0.0,
    val diesel: Boolean = false,
    val clatter: Double = 0.0,
    val accel: Double = 1.0,
    val pipe: Double = 1.4,
    val feedback: Double = 0.5,
    val fm: List<Triple<Double, Double, Double>> =
        listOf(Triple(90.0, 6.0, 1.3), Triple(500.0, 4.0, 2.0), Triple(1800.0, 2.0, 2.0)),
    val rasp: Double = 0.25,
    val muffler: Double = 700.0,
    val pops: Double = 0.05,
    val burble: Double = 0.5,
    val drive: Double = 2.2,
    val runner: Double = 0.5,
) {
    val isTurbo get() = induction == "turbo"
    val isSupercharged get() = induction == "sc"
}

